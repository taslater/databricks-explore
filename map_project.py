"""Write PROJECT_MAP.md: a one-file snapshot of the repo for agents that can't run `ls`.

Usage:
    python map_project.py           # rewrite PROJECT_MAP.md
    python map_project.py --check   # exit 1 if PROJECT_MAP.md is stale (for pre-commit / CI)

File list comes from `git ls-files` (tracked + untracked-but-not-ignored), so .gitignore
decides what's in. Falls back to a directory walk if git isn't available.
Python files get their docstring summary and top-level signatures via ast.
No timestamps in the output, so the file only changes when the code does.
"""
from __future__ import annotations

import ast
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "PROJECT_MAP.md"
SKIP_DIRS = {".git", ".venv", "venv", "__pycache__", ".pytest_cache", "node_modules", ".claude", "data"}
SKIP_FILES = {OUT.name}


def list_files() -> list[Path]:
    try:
        out = subprocess.run(
            ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout
        paths = [ROOT / p for p in out.splitlines()]
    except (OSError, subprocess.CalledProcessError):
        paths = []
        for dirpath, dirnames, filenames in os.walk(ROOT):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            paths += [Path(dirpath) / f for f in filenames]
    keep = []
    for p in paths:
        rel = p.relative_to(ROOT)
        if p.is_file() and rel.name not in SKIP_FILES and not (set(rel.parts[:-1]) & SKIP_DIRS):
            keep.append(p)
    return sorted(keep, key=lambda p: (p.relative_to(ROOT).parent.as_posix(), p.name.lower()))


def first_line(doc: str | None) -> str:
    return doc.strip().splitlines()[0].strip() if doc and doc.strip() else ""


def describe_python(path: Path) -> list[str]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError) as e:
        return [f"  - (could not parse: {e.__class__.__name__})"]
    lines = []
    if summary := first_line(ast.get_docstring(tree)):
        lines.append(f"  - {summary}")
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""
            doc = first_line(ast.get_docstring(node))
            lines.append(f"  - `def {node.name}({ast.unparse(node.args)}){ret}`" + (f": {doc}" if doc else ""))
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            doc = first_line(ast.get_docstring(node))
            lines.append(f"  - `class {node.name}({bases})`" + (f": {doc}" if doc else ""))
    return lines


def describe_markdown(path: Path) -> list[str]:
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("#"):
            return [f"  - {line.lstrip('#').strip()}"]
    return []


def describe_json(path: Path) -> list[str]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        return ["  - (invalid JSON)"]
    if isinstance(data, dict):
        title = data.get("title") or data.get("description")
        keys = ", ".join(list(data)[:12])
        return [f"  - {title}"] * bool(title) + [f"  - keys: {keys}"]
    return []


DESCRIBERS = {".py": describe_python, ".md": describe_markdown, ".json": describe_json}


def render() -> str:
    files = list_files()
    out = [
        "# PROJECT_MAP",
        "",
        "Generated by `python map_project.py`. Do not edit by hand.",
        f"Root: `databricks-explore` | files: {len(files)}",
        "",
    ]
    current_dir = None
    for p in files:
        rel = p.relative_to(ROOT)
        d = rel.parent.as_posix()
        if d != current_dir:
            current_dir = d
            out += ["", f"## {'/' if d == '.' else d + '/'}", ""]
        size = p.stat().st_size
        out.append(f"- `{rel.as_posix()}` ({size:,} B)" + (" (empty)" if size == 0 else ""))
        if fn := DESCRIBERS.get(p.suffix.lower()):
            out += fn(p)
    return "\n".join(out).replace("\n\n\n", "\n\n") + "\n"


def main() -> int:
    text = render()
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if "--check" in sys.argv:
        if text != old:
            print(f"{OUT.name} is stale; run: python map_project.py")
            return 1
        return 0
    if text != old:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.name}")
    else:
        print(f"{OUT.name} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
